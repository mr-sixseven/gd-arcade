#!/usr/bin/env node
/**
 * Refreshes the central GD Arcade snapshots from public sources.
 *
 *   node scripts/fetch-meta.mjs
 *
 * Produces:
 *   data/levels.js     level stats + Newgrounds song ids (GDBrowser)
 *   data/songs.js      authorised Newgrounds streaming URLs for custom songs
 *   data/demonlist.js  Pointercrate top-100 ranking snapshot
 *
 * No dependencies, Node 18+. Please be gentle with the public APIs.
 */

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const UA = "GD-Arcade/1.0 (static fan project; data refresh)";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const normKey = (value) => String(value || "").toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, " ").trim();
const decodeEntities = (value) => String(value || "")
  .replace(/&amp;/g, "&")
  .replace(/&quot;/g, '"')
  .replace(/&#0?39;|&apos;/g, "'")
  .replace(/&lt;/g, "<")
  .replace(/&gt;/g, ">")
  .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)));

async function get(url, tries = 4, as = "json") {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (res.status === 429 || res.status >= 500) throw new Error("HTTP " + res.status);
      if (!res.ok) throw new Error("HTTP " + res.status);
      return as === "json" ? await res.json() : await res.text();
    } catch (err) {
      if (i === tries - 1) throw err;
      await sleep(900 * (i + 1));
    }
  }
}

function loadBrowserScript(file, globalName) {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(file, ctx);
  return ctx.window[globalName];
}

async function main() {
  const levelsSource = await readFile(join(ROOT, "data/levels.js"), "utf8");
  const levels = loadBrowserScript(levelsSource, "GDLE_LEVELS");
  console.log(`Loaded ${levels.length} levels.`);

  // Keep the previous catalogue as a fallback: Newgrounds sometimes blocks
  // server-side page requests, and a failed refresh must not erase playable
  // stream URLs that were already verified.
  let existingSongs = [];
  try {
    existingSongs = loadBrowserScript(await readFile(join(ROOT, "data/songs.js"), "utf8"), "GD_SONGS") || [];
    console.log(`Loaded ${existingSongs.length} existing songs as fallback.`);
  } catch {
    console.warn("No existing song catalogue; a failed Newgrounds fetch will leave Songle empty.");
  }
  const existingSongById = new Map(existingSongs.map((song) => [String(song.id), song]));

  // ---- Pointercrate ranking snapshot ----------------------------------
  // A failed or empty fetch must never overwrite a good snapshot: fall back to
  // the existing demonlist file and skip reconciliation only if no copy exists.
  let ranked = null;
  try {
    const fetched = await get("https://pointercrate.com/api/v2/demons/listed/?limit=100");
    if (Array.isArray(fetched) && fetched.length) {
      ranked = fetched;
      console.log(`Pointercrate: ${ranked.length} ranked demons.`);
    } else {
      console.warn("Pointercrate returned no demons; keeping the existing snapshot.");
    }
  } catch (err) {
    console.warn("Pointercrate unavailable:", err.message);
  }

  let demonlist = [];
  let haveDemonSnapshot = false;
  if (ranked) {
    demonlist = ranked.map((d) => ({
      position: d.position,
      name: decodeEntities(d.name),
      creator: d.publisher?.name || d.creators?.[0]?.name || "Unknown",
      verifier: d.verifier?.name || null,
      video: d.video || null,
      source: "Pointercrate"
    }));
    haveDemonSnapshot = true;
    await writeFile(
      join(ROOT, "data/demonlist.js"),
      `/* Generated by scripts/fetch-meta.mjs — Pointercrate snapshot ${new Date().toISOString().slice(0, 10)}. */\n` +
        `window.GD_DEMONLIST = ${JSON.stringify(demonlist, null, 2)};\n`
    );
  } else {
    try {
      const existing = await readFile(join(ROOT, "data/demonlist.js"), "utf8");
      demonlist = loadBrowserScript(existing, "GD_DEMONLIST") || [];
      haveDemonSnapshot = demonlist.length > 0;
      console.warn(`Keeping existing demonlist snapshot (${demonlist.length} demons).`);
    } catch {
      console.warn("No existing demonlist snapshot found; demon fields will be left untouched.");
    }
  }

  const demonMeta = new Map();
  for (const demon of demonlist) {
    const key = normKey(demon.name);
    if (!demonMeta.has(key)) demonMeta.set(key, []);
    demonMeta.get(key).push(demon);
  }

  // ---- Song ids from GDBrowser ----------------------------------------
  // Seed from the current level snapshot so a GDBrowser failure cannot drop a
  // song id that we already know.
  const songIds = new Map();
  for (const level of levels) {
    const sid = level.songId ? String(level.songId) : null;
    if (!sid) continue;
    const known = existingSongById.get(sid);
    songIds.set(sid, {
      id: sid,
      name: known?.name || level.song || "Unknown song",
      artist: known?.artist || level.songAuthor || "Unknown artist"
    });
  }
  const enriched = [];
  let fetched = 0;

  for (const level of levels) {
    const out = { ...level };
    try {
      const raw = await get(`https://gdbrowser.com/api/level/${encodeURIComponent(level.id)}`);
      const sid = String(raw.songID ?? raw.customSong ?? "0");
      out.songId = /^\d+$/.test(sid) && sid !== "0" ? sid : null;
      out.officialSong = Number(raw.officialSong) || 0;
      out.songLink = raw.songLink && raw.songLink !== "-" ? raw.songLink : null;
      out.difficultyFace = raw.difficultyFace || null;
      if (out.songId) songIds.set(out.songId, { name: raw.songName, artist: raw.songAuthor, id: out.songId });
      fetched++;
    } catch (err) {
      // Preserve the last known song metadata on a transient API failure.
      console.warn(`  ${level.name}: ${err.message} — keeping previous song metadata`);
    }

    if (haveDemonSnapshot) {
      // Clear first so levels that dropped off the ranking do not keep stale data.
      out.demonPosition = null;
      out.verifier = null;
      const candidates = demonMeta.get(normKey(level.name)) || [];
      const meta = candidates.find((entry) => normKey(entry.creator) === normKey(level.creator)) || (candidates.length === 1 ? candidates[0] : null);
      if (meta) {
        out.demonPosition = meta.position;
        out.verifier = meta.verifier;
      }
    }
    enriched.push(out);
    process.stdout.write(`\rGDBrowser ${fetched}/${levels.length}`);
    await sleep(220);
  }
  console.log("");

  await writeFile(
    join(ROOT, "data/levels.js"),
    `/* GD Arcade central level database — generated by scripts/fetch-meta.mjs.\n` +
      ` * ${enriched.length} levels · snapshot ${new Date().toISOString().slice(0, 10)}\n` +
      ` * Data: gdbrowser.com + pointercrate.com. Geometry Dash is a game by RobTop Games.\n` +
      ` */\n` +
      `window.GD_LEVELS = ${JSON.stringify(enriched, null, 2)};\n` +
      `window.GDLE_LEVELS = window.GD_LEVELS;\n`
  );

  // ---- Resolve Newgrounds stream URLs ---------------------------------
  const songs = [];
  const entries = [...songIds.values()];
  console.log(`Resolving ${entries.length} Newgrounds songs…`);

  let consecutiveBlocks = 0;
  let newgroundsBlocked = false;
  for (let i = 0; i < entries.length; i++) {
    const song = entries[i];
    const prior = existingSongById.get(String(song.id));
    let resolved = null;

    if (!newgroundsBlocked) {
      try {
        const html = await get(`https://www.newgrounds.com/audio/listen/${song.id}`, 2, "text");
        const m = html.match(/https:\/\/audio\.ngfiles\.com\/[^"'\s]+?\.mp3[^"'\s]*/);
        const title = html.match(/<title>([^<]+)</)?.[1]?.trim();
        if (m) {
          resolved = {
            id: song.id,
            name: decodeEntities(title || song.name || "Unknown song"),
            artist: decodeEntities(song.artist || "Unknown artist"),
            audioUrl: decodeEntities(m[0]),
            pageUrl: `https://www.newgrounds.com/audio/listen/${song.id}`,
            source: "Newgrounds"
          };
          consecutiveBlocks = 0;
        }
      } catch (err) {
        // Newgrounds serves 403 to server-side requests from some networks.
        // After a few in a row, stop hammering it and reuse the snapshot.
        if (/HTTP 403/.test(err.message) && ++consecutiveBlocks >= 3) {
          newgroundsBlocked = true;
          console.warn("Newgrounds is blocking page requests; reusing cached stream URLs.");
        }
      }
    }

    if (resolved) songs.push(resolved);
    else if (prior) songs.push(prior);
    else console.warn(`  ${song.id}: no page data and no cached stream URL — skipped`);

    if ((i + 1) % 10 === 0) console.log(`  ${i + 1}/${entries.length}`);
    await sleep(newgroundsBlocked ? 0 : 180);
  }

  if (songs.length === 0) {
    console.warn("No songs resolved; leaving data/songs.js untouched.");
    console.log("Done. 0 playable songs (existing catalogue preserved).");
    return;
  }

  await writeFile(
    join(ROOT, "data/songs.js"),
    `/* GD Arcade song catalogue — generated by scripts/fetch-meta.mjs.\n` +
      ` * ${songs.length} songs · snapshot ${new Date().toISOString().slice(0, 10)}\n` +
      ` * Audio is streamed from Newgrounds' official CDN and linked back to each artist's page.\n` +
      ` */\n` +
      `window.GD_SONGS = ${JSON.stringify(songs, null, 2)};\n`
  );

  console.log(`Done. ${songs.length} playable songs.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
